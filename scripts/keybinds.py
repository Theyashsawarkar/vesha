#!/usr/bin/env python3
"""Writes the `# keybind:` lines in vesha/tui.py from its BINDS table (the
lines Vayu's keybinding search reads), between the two marker comments.

    scripts/keybinds.py           rewrite them
    scripts/keybinds.py --check   exit 1 if they're out of date (CI)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from vesha import tui  # noqa: E402

START = "# --- keybindings (generated by scripts/keybinds.py from BINDS: don't edit by hand) ---"
END = "# --- end keybindings ---"


def render(text):
    a, b = text.index(START) + len(START), text.index(END)
    return text[:a] + "\n" + "\n".join(tui.keybind_lines()) + "\n" + text[b:]


def main():
    path = ROOT / "vesha" / "tui.py"
    text = path.read_text()
    new = render(text)
    if "--check" in sys.argv:
        if new != text:
            print("vesha/tui.py: the keybind lines are out of date: run scripts/keybinds.py", file=sys.stderr)
            return 1
        print("keybind lines up to date")
        return 0
    path.write_text(new)
    print(f"wrote {len(tui.keybind_lines())} keybind lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
