    # ---------------------------------------------------------------- actions
    def save_reload(self):
        core.save(self.st)
        self.st = core.load()

    def act_switch(self):
        n = self.current()
        if not n:
            return
        if n == self.st["default"]:
            self.toast(f"{n} is already the active account", "warn")
            return
        try:
            core.activate(self.st, n)
        except core.VeshaError as e:
            self.toast(str(e), "err")
            return
        self.st = core.load()
        core.signal_bar()
        self.toast(f"✓ {n} is active: running claude sessions use it from their next message, new ones too")

    def act_pause(self):
        n = self.current()
        if n:
            acc = self.st["accounts"][n]
            acc["paused"] = not acc.get("paused")
            self.save_reload()
            self.toast(f"{n} " + ("won't be picked by auto-switching" if self.st["accounts"][n]["paused"] else "can be picked again"))

    def act_map(self):
        n = self.current()
        if n:
            try:
                f = core.map_folder(self.st, n, self.cwd)
                self.st = core.load()
                self.toast(f"✓ {f.replace(core.HOME, '~')} and below always use {n}")
            except core.VeshaError as e:
                self.toast(str(e), "err")

    def act_copy(self):
        n = self.current()
        email = self.st["accounts"].get(n, {}).get("email") if n else None
        if not email:
            return
        try:
            subprocess.run(["wl-copy"], input=email, text=True, timeout=3)
            self.toast(f"copied {email}")
        except (OSError, subprocess.TimeoutExpired):
            self.toast("couldn't copy (no wl-copy)", "err")

    def act_remove(self):
        if self.focus == "folders":
            rules = self.folders()
            if not rules:
                return
            f, n = rules[self.sel["folders"]]

            def do():
                core.unmap_folder(self.st, f)
                self.st = core.load()
                self.sel["folders"] = max(0, min(self.sel["folders"], len(self.folders()) - 1))
                self.toast(f"✓ {f} follows the active account again")
            self.ask(f"Remove the rule {f} → {n}?", do)
            return
        n = self.current()
        if not n:
            return
        what = "forget it (the login stays in ~/.claude)" if self.st["accounts"][n].get("main") else "delete its profile and login"

        def do():
            core.remove(self.st, n)
            self.st = core.load()
            self.sel["accounts"] = max(0, min(self.sel["accounts"], len(self.names()) - 1))
            self.toast(f"✓ removed {n}")
        self.ask(f"Remove {n}? This will {what}.", do)

    def act_rename(self):
        n = self.current()
        if not n:
            return

        def done(new):
            try:
                core.rename(self.st, n, new.strip())
                self.st = core.load()
                self.toast(f"✓ {n} is now {new.strip()}")
            except core.VeshaError as e:
                self.toast(str(e), "err")
        self.prompt("RENAME", f"rename {n} to: ", n, done)

    def act_add(self):
        def got_email(name, email):
            email = email.strip()
            if email and not re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", email):
                self.toast(f"“{email}” isn't an email address", "err")
                return
            try:
                self.signin = core.SignIn(self.st, name, email)
            except core.VeshaError as e:
                self.toast(str(e), "err")
                return
            self.code_buf, self.mode, self.signin_insert = "", "INSERT", True   # the code field takes a paste

        def got_name(name):
            name = name.strip()
            try:
                core.check_name(name)
                if name in self.st["accounts"]:
                    raise core.VeshaError(f"there's already an account called {name}")
            except core.VeshaError as e:
                self.toast(str(e), "err")
                return
            self.prompt("ADD", f"{name}'s email (Enter to type it in the browser instead): ", "", lambda e: got_email(name, e))
        self.prompt("ADD", "name for the new account (e.g. work, client-x): ", "", got_name)

    def signin_key(self, tok):
        """The sign-in code field, in INSERT mode."""
        if tok == "<Esc>":
            self.signin_insert, self.mode = False, "NORMAL"
        elif tok == "<CR>":
            self.act_send_code()
        elif tok == "<C-o>":
            self.act_open_page()
        elif tok == "<C-y>":
            self.act_copy_link()
        elif tok == "<BS>":
            self.code_buf = self.code_buf[:-1]
        elif tok == "<C-u>":
            self.code_buf = ""
        elif len(tok) == 1:
            self.code_buf += tok
        return True

    def act_send_code(self):
        if self.signin and self.code_buf.strip():
            self.signin.send_code(self.code_buf)
            self.code_buf = ""

    def act_open_page(self):
        si = self.signin
        if si and si.url:
            subprocess.Popen(["xdg-open", si.url], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            self.toast("opened the sign-in page")

    def act_copy_link(self):
        si = self.signin
        if si and si.url:
            try:
                subprocess.run(["wl-copy"], input=si.url, text=True, timeout=3)
                self.toast("copied the sign-in link")
            except (OSError, subprocess.TimeoutExpired):
                self.toast("couldn't copy (no wl-copy)", "err")

    def act_cancel_signin(self):
        if self.signin:
            self.signin.cancel()
            self.signin, self.signin_insert, self.mode = None, False, "NORMAL"
            self.toast("sign-in cancelled", "warn")

    def signin_poll(self):
        si = self.signin
        if not si or not si.done:
            return
        self.signin, self.signin_insert, self.mode = None, False, "NORMAL"
        try:
            who = si.finish(self.st)
        except core.VeshaError as e:
            self.toast(f"✗ {si.name} wasn't added: {e}", "err")
            return
        self.st = core.load()
        self.focus = "accounts"
        if si.name in self.names():
            self.sel["accounts"] = self.names().index(si.name)
        self.toast(f"✓ {si.name} signed in ({who['email']}, {who['plan']}): Enter makes it active")
        self.refresh_usage(True)

    def ask(self, question, cb):
        self.mode = "CONFIRM"
        self.confirm = (question, cb)

    def prompt(self, _what, text, initial, cb):
        self.mode = "INSERT"
        self.input = (text, initial, cb)

    # ---------------------------------------------------------------- keys
    def move(self, delta):
        size = len(self.names()) if self.focus == "accounts" else len(self.folders())
        if size:
            self.sel[self.focus] = max(0, min(size - 1, self.sel[self.focus] + delta))

    def view(self):
        return SIGNIN if self.signin else self.focus

    def keymap(self):
        """The NORMAL-mode keys of the view you're in."""
        v = self.view()
        return Keymap([b for b in BINDS if b.applies("normal", v)])

    def palette_matches(self):
        query = self.palette[0] if self.palette else ""
        rows, seen = [], {}
        for keys_, what, b in palette_rows(self.keymap()):
            if b.action == "palette":
                continue
            if (what, b.action) in seen:   # one row per action: "Space e n · c w"
                i = seen[(what, b.action)]
                rows[i] = (rows[i][0] + " · " + keys_, what, rows[i][2])
                continue
            seen[(what, b.action)] = len(rows)
            rows.append((keys_, what, b))
        return [r for r in rows if fuzzy(query, f"{r[1]} {r[0]}")]

    def key(self, ch):
        tok = curses_token(ch)
        if tok is None:
            return True
        if self.palette is not None:
            return self.palette_key(tok)
        if self.help:
            if tok in ("?", "<Esc>", "q"):
                self.help = False
            return True
        if self.confirm:
            question, cb = self.confirm
            self.confirm, self.mode = None, "NORMAL"
            if tok == "y":   # only y says yes: a stray Enter never removes anything
                try:
                    cb()
                except core.VeshaError as e:
                    self.toast(str(e), "err")
            else:
                self.toast("cancelled", "warn")
            return True
        if self.input:
            return self.input_key(tok)
        if self.signin and self.signin_insert:
            return self.signin_key(tok)
        had = bool(self.machine.count)
        r = self.machine.feed(self.keymap(), tok)
        if r.kind == "pending":
            if r.seq and len(r.seq) == len(tok):
                self.pending_at = time.time()
            return True
        if r.kind == "cancel":
            return True
        if r.kind == "unknown":
            self.toast(f"{spell(r.seq)} isn't a key here: ? lists them", "warn")
            return True
        return self.run_action(r.bind.action, r.count, had)

    def input_key(self, tok):
        """A prompt (search, rename, add) in INSERT mode."""
        text, buf, cb = self.input
        if tok == "<Esc>":
            self.input, self.mode = None, "NORMAL"
            if self.filter and text.startswith("/"):
                self.filter = ""
        elif tok == "<CR>":
            self.input, self.mode = None, "NORMAL"
            cb(buf)
        elif tok == "<BS>":
            self.input = (text, buf[:-1], cb)
        elif tok == "<C-u>":
            self.input = (text, "", cb)
        elif tok in ("<C-j>", "<Down>"):
            self.move(1)
        elif tok in ("<C-k>", "<Up>"):
            self.move(-1)
        elif len(tok) == 1:
            self.input = (text, buf + tok, cb)
        if self.input and text.startswith("/") and tok not in ("<C-j>", "<C-k>", "<Down>", "<Up>"):
            self.filter = self.input[1]
            self.jump_match(0)
        return True

    def palette_key(self, tok):
        query, sel = self.palette
        rows = self.palette_matches()
        if tok == "<Esc>":
            self.palette = None
        elif tok == "<CR>":
            self.palette = None
            if rows:
                return self.run_action(rows[min(sel, len(rows) - 1)][2].action, 1, False)
        elif tok in ("<C-j>", "<Down>", "<Tab>"):
            self.palette = [query, min(sel + 1, max(0, len(rows) - 1))]
        elif tok in ("<C-k>", "<Up>", "<S-Tab>"):
            self.palette = [query, max(0, sel - 1)]
        elif tok == "<BS>":
            self.palette = [query[:-1], 0]
        elif tok == "<C-u>":
            self.palette = ["", 0]
        elif len(tok) == 1:
            self.palette = [query + tok, 0]
        return True

    def run_action(self, action, n, had):
        """Runs one bound action; False quits the switcher."""
        verb, _, arg = action.partition(":")
        size = len(self.names()) if self.focus == "accounts" else len(self.folders())
        acc = self.focus == "accounts" and not self.signin
        if verb == "move":
            self.move(int(arg) * n)
        elif verb in ("top", "bottom"):
            if size:
                i = (n - 1) if had else (0 if verb == "top" else size - 1)
                self.sel[self.focus] = max(0, min(i, size - 1))
        elif verb == "half":
            self.move(int(arg) * n * max(1, (self.scr.getmaxyx()[0] - 16) // 2))
        elif verb == "tab":
            self.focus = ("folders" if self.focus == "accounts" else "accounts") if arg == "other" else arg
        elif verb == "switch" and acc:
            self.act_switch()
        elif verb == "run" and acc:
            if self.current():
                self.after = ("run", self.current())
                return False
        elif verb == "refresh":
            self.refresh_usage(True)
            self.toast("asking Anthropic for usage… (running claude here moved from r to o)")
        elif verb == "moved":
            new, _, what = arg.partition(":")
            self.toast(f"that key moved: {what} is {new} now", "warn")
        elif verb == "pause" and acc:
            self.act_pause()
        elif verb == "map" and acc:
            self.act_map()
        elif verb == "add":
            self.act_add()
        elif verb == "rename" and acc:
            self.act_rename()
        elif verb == "remove":
            self.act_remove()
        elif verb == "copy":
            self.act_copy_link() if arg == "link" else self.act_copy()
        elif verb == "search":
            self.filter = ""
            self.prompt("FILTER", "/", "", lambda s: self.jump_match(0) if s else None)
        elif verb == "match":
            self.jump_match(int(arg))
        elif verb == "goto":
            if self.st["default"] in self.names():
                self.focus = "accounts"
                self.sel["accounts"] = self.names().index(self.st["default"])
        elif verb == "help":
            self.help = True
        elif verb == "palette":
            self.palette = ["", 0]
        elif verb == "insert":
            self.signin_insert, self.mode = True, "INSERT"
        elif verb == "send":
            self.act_send_code()
        elif verb == "open":
            self.act_open_page()
        elif verb == "cancel":
            self.act_cancel_signin()
        elif verb == "quit":
            return False
        return True

    def jump_to(self, n):
        names = self.names()
        if 1 <= n <= len(names):
            self.sel["accounts"] = n - 1
            self.focus = "accounts"

    def jump_match(self, step):
        if not self.filter:
            return
        names = self.names()
        hits = [i for i, n in enumerate(names) if self.filter.lower() in f"{n} {self.st['accounts'][n].get('email', '')}".lower()]
        if not hits:
            self.toast(f"no account matches “{self.filter}”", "warn")
            return
        cur = self.sel["accounts"]
        if step == 0:
            nxt = next((i for i in hits if i >= cur), hits[0])
        elif step > 0:
            nxt = next((i for i in hits if i > cur), hits[0])
        else:
            nxt = next((i for i in reversed(hits) if i < cur), hits[-1])
        self.focus = "accounts"
        self.sel["accounts"] = nxt

    def loop(self):
        curses.curs_set(0)
        self.scr.timeout(100)
        self.scr.keypad(True)
        curses.set_escdelay(25)
        while True:
            self.frame += 1
            self.signin_poll()
            self.draw()
            try:
                ch = self.scr.get_wch()
            except curses.error:
                continue
            except KeyboardInterrupt:
                return
            if ch == curses.KEY_RESIZE:
                continue
            if not self.key(ch):
                return
            if self.after:
                return


