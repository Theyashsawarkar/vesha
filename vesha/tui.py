    def overlay(self, bw, bh, title, at_bottom=False):
        """A rounded box drawn over the screen; returns its (y, x, w, h)."""
        h, w = self.scr.getmaxyx()
        bw, bh = min(w - 2, bw), min(h - 2, bh)
        y0 = h - 1 - bh if at_bottom else max(1, (h - bh) // 2)
        x0 = max(1, (w - bw) // 2)
        for i in range(bh):
            self.put(y0 + i, x0, " " * bw, self.a("text", sel=True))
        bord = self.a("border", sel=True) if "sel_border" in self.pairs else self.a("faint", sel=True)
        self.put(y0, x0, "╭" + "─" * (bw - 2) + "╮", bord)
        for i in range(1, bh - 1):
            self.put(y0 + i, x0, "│", bord)
            self.put(y0 + i, x0 + bw - 1, "│", bord)
        self.put(y0 + bh - 1, x0, "╰" + "─" * (bw - 2) + "╯", bord)
        self.put(y0, x0 + 2, f" {title} ", self.a("chip_peach", True))
        return y0, x0, bw, bh

    def draw_which(self):
        """The keys that can follow what's been typed (Space, g, d…), and
        their groups: a which-key strip over the status line."""
        km = self.keymap()
        nxt = sorted(km.next_keys(self.machine.pending), key=lambda r: (r[2], r[0].lower(), r[0]))
        if not nxt:
            return
        h, w = self.scr.getmaxyx()
        cell = min(38, max(len(spell(t)) + len(what) for t, what, _ in nxt) + 4)
        cols = max(1, min(4, (w - 6) // cell))
        rows = (len(nxt) + cols - 1) // cols
        y0, x0, bw, bh = self.overlay(cols * cell + 4, rows + 3, f"{self.machine.typed()} ›", at_bottom=True)
        for i, (tok, what, group) in enumerate(nxt):
            r, c = i % rows, i // rows
            cx = self.put(y0 + 1 + r, x0 + 2 + c * cell, spell(tok), self.a("peach", True, True))
            self.put(y0 + 1 + r, cx + 1, what[: cell - len(spell(tok)) - 2], self.a("sky" if group else "sub", sel=True))
        self.put(y0 + bh - 2, x0 + 2, "Esc cancels", self.a("dim", sel=True))

