    def draw_help(self):
        """The keys, in as many columns as the terminal fits (3, 2 or 1)."""
        HELP = help_rows(self.keymap()) or [("Keys", [])]
        h, w = self.scr.getmaxyx()
        key_w = max(len(k) for _, rows in HELP for k, _ in rows) + 2
